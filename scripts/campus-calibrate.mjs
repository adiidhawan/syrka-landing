// Re-derives the SYRKA Campus demo calibration from real job postings.
//
//   npm run campus:calibrate
//
// Reads the live-openings sources (Himalayas, plus any partner boards in CAMPUS_PARTNER_BOARDS) and writes
// lib/campus/calibration.ts: the share of postings in each role family that mention each skill. Only these aggregate
// shares are stored; no posting is saved. Set HIMALAYAS_API_KEY for higher rate limits.
// Needs Node 23.6+ (or 22.18+) to import the TypeScript module directly.
import { writeFileSync } from 'node:fs'
import { fetchLiveJobs, parsePartnerBoards } from '../lib/campus/live-jobs.ts'

// Entry- and mid-level postings ask for much the same skills; reading both gives role families a usable sample.
const result = await fetchLiveJobs({
  partners: parsePartnerBoards(process.env.CAMPUS_PARTNER_BOARDS), himalayasKey: process.env.HIMALAYAS_API_KEY,
  seniority: ['Entry-level', 'Mid-level'], maxPages: 10, timeoutMs: 20_000,
})
const failed = result.sources.filter(s => !s.ok)
if (!result.jobs.length) throw new Error('No postings fetched; calibration left unchanged.')

const families = {}
for (const job of result.jobs) (families[job.family] ??= []).push(job)

const table = {}
for (const [family, jobs] of Object.entries(families)) {
  const counts = {}
  for (const j of jobs) for (const id of new Set([...j.required, ...j.preferred, ...j.extracted])) counts[id] = (counts[id] ?? 0) + 1
  table[family] = {
    postings: jobs.length,
    companies: new Set(jobs.map(j => j.company)).size,
    skills: Object.entries(counts)
      .map(([skillId, n]) => ({ skillId, share: Math.round((n / jobs.length) * 100) / 100 }))
      .filter(s => s.share >= 0.2)
      .sort((a, b) => b.share - a.share || a.skillId.localeCompare(b.skillId)),
  }
}

const date = result.fetchedAt.slice(0, 10)
writeFileSync(new URL('../lib/campus/calibration.ts', import.meta.url), `// Generated by scripts/campus-calibrate.mjs on ${date}. Do not edit by hand; re-run the script instead.
//
// For each role family: how many real Indian postings were read, from how many companies, and the share of those
// postings that mention each skill anywhere in the posting (skills mentioned by fewer than 20% are left out). Mentions
// are mapped from posting text by lib/campus/live-jobs.ts, so treat the shares as indicative, not exact.

import type { RoleFamily } from './live-jobs'

export interface FamilyCalibration {
  postings: number
  companies: number
  skills: { skillId: string; share: number }[]
}

export const CALIBRATION_DATE = '${date}'
export const CALIBRATION_SOURCE = '${result.jobs.length} entry- and mid-level postings open to candidates in India, from ${result.sources.filter(s => s.ok).map(s => s.label).join(', ')}'

export const CALIBRATION: Partial<Record<RoleFamily, FamilyCalibration>> = {
${Object.entries(table).sort((a, b) => b[1].postings - a[1].postings).map(([f, t]) => `  ${f}: {
    postings: ${t.postings},
    companies: ${t.companies},
    skills: [
${t.skills.map(k => `      { skillId: '${k.skillId}', share: ${k.share} },`).join('\n')}
    ],
  },`).join('\n')}
}
`)
console.log(`Calibrated ${Object.keys(table).length} families from ${result.jobs.length} postings (${date}).${failed.length ? ` Failed boards: ${failed.map(s => s.label).join(', ')}` : ''}`)
