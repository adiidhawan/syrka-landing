// Builds lib/campus/onet-role-skills.ts: an internal role-to-skill mapping from the O*NET 31.0 Software Skills file.
//
//   1. Download https://www.onetcenter.org/dl_files/database/db_31_0_csv/software_skills.csv into a folder
//   2. npm run campus:onet -- <that folder>
//
// For each SYRKA role family, the listed O*NET occupations' software examples are mapped to SYRKA catalogue skills
// with the same keyword patterns used for job postings. Only software/technology skills can be mapped this way.
// The output is used internally to judge which skills are relevant to a target role; it is never shown as a
// student's own evidence. O*NET is CC BY 4.0: keep the attribution in lib/campus/sources.ts when this file is used.
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { SKILL_PATTERNS } from '../lib/campus/live-jobs.ts'

const dir = process.argv[2]
if (!dir) throw new Error('Usage: npm run campus:onet -- <folder containing software_skills.csv>')

const FAMILY_OCCUPATIONS = {
  frontend: ['15-1254.00', '15-1255.00'],
  backend: ['15-1252.00'],
  fullstack: ['15-1252.00', '15-1254.00'],
  mobile: ['15-1252.00'],
  other_eng: ['15-1252.00'],
  qa: ['15-1253.00'],
  data_analyst: ['15-2051.01', '15-2041.00'],
  data_engineer: ['15-1243.00', '15-1242.00'],
  ml: ['15-2051.00', '15-1221.00'],
  design: ['15-1255.00', '27-1024.00'],
  platform: ['15-1244.00', '15-1241.00'],
}

// Minimal CSV parser for quoted fields.
function parseCsv(text) {
  const rows = []
  let row = [], field = '', quoted = false
  for (let i = 0; i < text.length; i++) {
    const c = text[i]
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i++ } else if (c === '"') quoted = false; else field += c
    } else if (c === '"') quoted = true
    else if (c === ',') { row.push(field); field = '' }
    else if (c === '\n') { row.push(field.replace(/\r$/, '')); rows.push(row); row = []; field = '' }
    else field += c
  }
  if (field || row.length) { row.push(field); rows.push(row) }
  return rows
}

const [header, ...rows] = parseCsv(readFileSync(join(dir, 'software_skills.csv'), 'utf8'))
const col = name => header.indexOf(name)
const [cCode, cTitle, cExample, cHot, cDemand] = ['O*NET-SOC Code', 'Title', 'Workplace Example', 'Hot Technology', 'In Demand'].map(col)
if ([cCode, cTitle, cExample, cHot, cDemand].includes(-1)) throw new Error(`Unexpected columns: ${header.join(', ')}`)

const titles = {}
const bySoc = {}
for (const r of rows) {
  if (!r[cCode]) continue
  titles[r[cCode]] = r[cTitle]
  for (const s of SKILL_PATTERNS) {
    if (!s.re.test(r[cExample])) continue
    const entry = ((bySoc[r[cCode]] ??= {})[s.id] ??= { hot: false, inDemand: false, examples: new Set() })
    entry.hot ||= r[cHot] === 'Y'
    entry.inDemand ||= r[cDemand] === 'Y'
    entry.examples.add(r[cExample])
  }
}

const out = {}
for (const [family, socs] of Object.entries(FAMILY_OCCUPATIONS)) {
  const skills = {}
  for (const soc of socs) for (const [id, e] of Object.entries(bySoc[soc] ?? {})) {
    const cur = (skills[id] ??= { hot: false, inDemand: false })
    cur.hot ||= e.hot
    cur.inDemand ||= e.inDemand
  }
  out[family] = {
    occupations: socs.filter(s => titles[s]).map(s => ({ code: s, title: titles[s] })),
    skills: Object.entries(skills).map(([skillId, e]) => ({ skillId, ...e })).sort((a, b) => a.skillId.localeCompare(b.skillId)),
  }
}

const body = Object.entries(out).map(([f, v]) => `  ${f}: {
    occupations: [${v.occupations.map(o => `{ code: '${o.code}', title: ${JSON.stringify(o.title)} }`).join(', ')}],
    skills: [
${v.skills.map(s => `      { skillId: '${s.skillId}', hot: ${s.hot}, inDemand: ${s.inDemand} },`).join('\n')}
    ],
  },`).join('\n')

writeFileSync(new URL('../lib/campus/onet-role-skills.ts', import.meta.url), `// Generated by scripts/campus-onet.mjs from the O*NET 31.0 Software Skills file. Do not edit by hand.
//
// Includes information from the O*NET 31.0 Database by the U.S. Department of Labor, Employment and Training
// Administration (USDOL/ETA), used under CC BY 4.0 (https://creativecommons.org/licenses/by/4.0/). SYRKA has modified
// and mapped portions of this data: software examples were matched to SYRKA catalogue skills by keyword. USDOL/ETA
// has not approved, endorsed, or tested these modifications. O*NET® is a trademark of USDOL/ETA.
//
// Internal use only: decides which skills are relevant to a target role. Never shown as a student's evidence.

import type { RoleFamily } from './live-jobs'

export interface OnetFamilyMapping {
  occupations: { code: string; title: string }[]
  /** Catalogue skills found among the occupations' software examples, with O*NET's Hot Technology / In Demand flags. */
  skills: { skillId: string; hot: boolean; inDemand: boolean }[]
}

export const ONET_VERSION = '31.0'

export const ONET_ROLE_SKILLS: Record<RoleFamily, OnetFamilyMapping> = {
${body}
}
`)
